#!/usr/bin/env python3
"""The THREAT-SENSITIVE notes are a claim about the lists, so they are held
to the lists (§0z194, §0q).

    python -m tests.test_threat_notes
    python -m tests.test_threat_notes --mutate   # 3 mutations, exact sets

`tools/_threat_notes.py` is GENERATED by `run_threat_sweep list --write`
from the sweep's summaries, which are git-ignored resume state, so no check
can re-derive it. What can be checked is that it still describes the decks:

CASES
  A  every noted card is a nonland in its deck's STAGED list
  B  every noted card's `threat` in the staged list equals the threat the
     note was measured at
  C  `ablation.threat_note` renders a line for every noted card and ""
     for a card with no note (Sol Ring in karlov)
  D  every note has at least one move, and every move is +-3 (the sweep's
     delta)

A FAILURE MEANS: re-run `python -m diagnostics.run_threat_sweep` (screen,
confirm, then `list --write`) for that deck, or delete the note by hand and
say so. Never edit a number in the generated file.

MUTATIONS, WRITTEN BEFORE THE FIRST RUN, exact sets:
  karlov's Dawn of Hope cut from the staged list (a blank in its slot) -> A
  karlov's Exquisite Blood at threat 9.5 instead of 9.0              -> B
  `threat_note` returns "" for every card                             -> C

UNMUTATED (§0z15): D, a property of the generated file's shape.
"""
import dataclasses
import sys

import edhmc.pending as P
import tools.ablation as AB
from tools._threat_notes import THREAT_NOTES

MUTATE = "--mutate" in sys.argv
PASS, FAIL = [], []
_REAL_BUILD = P.build_pending
_REAL_NOTE = AB.threat_note


def check(label, ok, detail=""):
    (PASS if ok else FAIL).append(label.split(" ")[0])
    print(f"  {'PASS' if ok else 'FAIL'}  {label}"
          + ("" if ok else f"\n        {detail}"))


def run_cases():
    del PASS[:], FAIL[:]
    missing, moved = [], []
    for deck, cards in THREAT_NOTES.items():
        lst, _cmd = P.build_pending(deck)
        have = {c.name: c for c in lst if not c.is_land}
        for name, e in cards.items():
            if name not in have:
                missing.append(f"{deck}: {name}")
            elif have[name].threat != e["threat"]:
                moved.append(f"{deck}: {name} {e['threat']} -> "
                             f"{have[name].threat}")
    check("A every noted card is in its staged list", not missing,
          "; ".join(missing))
    check("B every noted card is at the threat it was measured at",
          not moved, "; ".join(moved))
    blank = [f"{d}: {n}" for d, cs in THREAT_NOTES.items() for n in cs
             if not AB.threat_note(d, n).startswith("THREAT-SENSITIVE")]
    check("C each note renders, and a card without one renders nothing",
          not blank and AB.threat_note("karlov", "Sol Ring") == "",
          "; ".join(blank))
    shape = [f"{d}: {n}" for d, cs in THREAT_NOTES.items()
             for n, e in cs.items()
             if not e["moves"] or any(abs(dl) != 3.0 for dl, _w in e["moves"])]
    check("D every note is a +-3 move", not shape, "; ".join(shape))
    return set(FAIL)


def main() -> int:
    if not MUTATE:
        print(f"THREAT-SENSITIVE notes against the staged lists "
              f"({sum(map(len, THREAT_NOTES.values()))} notes)\n")
        run_cases()
        print(f"\n{len(PASS)} passed, {len(FAIL)} failed")
        return 1 if FAIL else 0

    print("MUTATION RUN -- exact sets\n")

    def edit(deck_name, fn):
        def build(name, *a, **k):
            lst, cmd = _REAL_BUILD(name, *a, **k)
            return (fn(lst), cmd) if name == deck_name else (lst, cmd)
        return build

    def cut_dawn(lst):
        return [AB.blank_like(c, 1.0) if c.name == "Dawn of Hope" else c
                for c in lst]

    def bump_blood(lst):
        return [dataclasses.replace(c, threat=9.5)
                if c.name == "Exquisite Blood" else c for c in lst]

    muts = {
        "Dawn of Hope cut": ({"A"}, ("build", edit("karlov", cut_dawn))),
        "Exquisite Blood at 9.5": ({"B"}, ("build", edit("karlov",
                                                          bump_blood))),
        "threat_note renders nothing": ({"C"}, ("note", lambda d, n: "")),
    }
    bad = 0
    for label, (want, (what, fn)) in muts.items():
        print(f"-- {label}")
        if what == "build":
            P.build_pending = fn
        else:
            AB.threat_note = fn
        try:
            broke = run_cases()
        finally:
            P.build_pending = _REAL_BUILD
            AB.threat_note = _REAL_NOTE
        ok = broke == want
        bad += not ok
        print(f"   broke {sorted(broke) or 'nothing'}  expected "
              f"{sorted(want)}  {'OK' if ok else '!!! UNEXPECTED'}\n")
    print(f"{len(muts) - bad} passed, {bad} failed "
          f"({len(muts)} mutations, exact sets)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
