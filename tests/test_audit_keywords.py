#!/usr/bin/env python3
"""§0z197 E (queue item 46) -- `audit_cards` checks the hand-typed `haste`
and `lifelink` against Scryfall's `keywords`, and the check can fail.

    python -m tests.test_audit_keywords
    python -m tests.test_audit_keywords --mutate   # 3 mutations, exact sets

THE GAP. `Card.haste` and `Card.lifelink` are typed by hand in the deck
modules; flying, trample, deathtouch and the rest are generated by
`tools/tag_flying.py`, and `audit_cards` checked flying and indestructible
only. A hand list with no derivation and no check is §0q's shape. The census
found no wrong tag among 647 cards but Lorehold, the Historian's haste.

OFFLINE: every case is a synthetic Scryfall record against a `Card`, run
through `audit_cards.check` itself (the whole per-card check, so a call site
that stopped asking is caught too), keeping only the haste/lifelink
messages. Case G is the real commander out of the deck module.

CASES:
  A  a haste creature tagged haste                      -> no ERR
  B  a haste creature NOT tagged                        -> haste ERR
  C  a creature tagged haste that has no keyword        -> haste ERR
  D  a lifelink creature NOT tagged                     -> lifelink ERR
  E  a creature tagged lifelink that has no keyword     -> lifelink ERR
  F  an INSTANT whose keywords carry Haste (it grants it), untagged -> no ERR
  G  Lorehold, the Historian as the module builds it, "Flying, haste" -> no ERR

MUTATIONS, WRITTEN BEFORE THE RUN, exact sets:
  haste dropped from KEYWORD_TAGS                -> B, C
  lifelink dropped from KEYWORD_TAGS             -> D, E
  the permanents-only rule removed               -> F
"""
import sys

import tools.audit_cards as AC
from edhmc.engine import Card
from edhmc.decks import lorehold_v17

MUTATE = "--mutate" in sys.argv
PASS, FAIL = [], []


def card(name, types="Creature", haste=False, lifelink=False):
    return Card(name=name, types=frozenset(types.split("/")),
                cost={"gen": 1, "R": 1}, power=2 if "Creature" in types else 0,
                toughness=2 if "Creature" in types else 0,
                haste=haste, lifelink=lifelink)


def record(name, keywords, type_line="Creature — Test"):
    creature = type_line.startswith("Creature")
    sc = {"name": name, "type_line": type_line, "mana_cost": "{1}{R}",
          "cmc": 2.0, "keywords": list(keywords)}
    if creature:
        sc.update(power="2", toughness="2")
    return sc


def keyword_msgs(c, sc):
    return [m for sev, m in AC.check("test", c, sc)
            if m.startswith(("haste=", "lifelink="))]


def expect(label, c, sc, want):
    got = sorted(m.split("=")[0] for m in keyword_msgs(c, sc))
    ok = got == sorted(want)
    (PASS if ok else FAIL).append(label.split(" ")[0])
    print(f"  {'PASS' if ok else 'FAIL'}  {label}"
          + ("" if ok else f"   got {got}, want {sorted(want)}"))


def run_cases():
    global PASS, FAIL
    PASS, FAIL = [], []
    expect("A a haste creature tagged haste -> no ERR",
           card("A", haste=True), record("A", ["Haste"]), [])
    expect("B a haste creature NOT tagged -> haste ERR",
           card("B"), record("B", ["Haste"]), ["haste"])
    expect("C tagged haste, no keyword -> haste ERR",
           card("C", haste=True), record("C", []), ["haste"])
    expect("D a lifelink creature NOT tagged -> lifelink ERR",
           card("D"), record("D", ["Lifelink"]), ["lifelink"])
    expect("E tagged lifelink, no keyword -> lifelink ERR",
           card("E", lifelink=True), record("E", []), ["lifelink"])
    expect("F an instant that grants haste, untagged -> no ERR",
           card("F", types="Instant"), record("F", ["Haste"], "Instant"), [])
    cmd = lorehold_v17.COMMANDER
    expect("G Lorehold, the Historian as built -> no ERR", cmd,
           record(cmd.name, ["Flying", "Haste"],
                  "Legendary Creature — Elder Dragon")
           | {"mana_cost": "{3}{R}{W}", "cmc": 5.0, "power": "5",
              "toughness": "5"}, [])
    return set(FAIL)


def main() -> int:
    if not MUTATE:
        print("§0z197 E -- haste and lifelink against Scryfall's keywords\n")
        run_cases()
        print(f"\n{len(PASS)} passed, {len(FAIL)} failed")
        return 1 if FAIL else 0

    print("MUTATION RUN -- exact sets\n")
    real_tags, real_fn = AC.KEYWORD_TAGS, AC.keyword_tag_errors

    def no_permanent_rule(c, kw):
        out = []
        for attr, word in AC.KEYWORD_TAGS:
            if bool(getattr(c, attr, False)) != (word in kw):
                out.append(("ERR", f"{attr}=..., keywords {sorted(kw)}"))
        return out

    muts = {
        "haste dropped from KEYWORD_TAGS":
            (dict(tags=(("lifelink", "Lifelink"),)), {"B", "C"}),
        "lifelink dropped from KEYWORD_TAGS":
            (dict(tags=(("haste", "Haste"),)), {"D", "E"}),
        "the permanents-only rule removed":
            (dict(fn=no_permanent_rule), {"F"}),
    }
    bad = 0
    for label, (patch, want) in muts.items():
        print(f"-- {label}")
        AC.KEYWORD_TAGS = patch.get("tags", real_tags)
        AC.keyword_tag_errors = patch.get("fn", real_fn)
        try:
            broke = run_cases()
        finally:
            AC.KEYWORD_TAGS, AC.keyword_tag_errors = real_tags, real_fn
        ok = broke == want
        bad += (not ok)
        print(f"   broke {sorted(broke) or 'nothing'}  expected {sorted(want)}"
              f"  {'OK' if ok else '!!! UNEXPECTED'}\n")
    print(f"{len(muts) - bad} passed, {bad} failed "
          f"({len(muts)} mutations, exact sets)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
