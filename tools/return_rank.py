#!/usr/bin/env python3
"""The win-rate RANK a return effect reads (§0z277), GENERATED from a deck's
ablation cache -- never typed (§0q).

    python -m tools.return_rank            # print the ranking, check the file
    python -m tools.return_rank --write    # regenerate edhmc/decks/_return_rank.py

The owner, 2026-11-27, on azusa's Eternal Witness and Regrowth (the oracle
audit's Tier 4 item 15): "lets try highest winrate card instead of highest
CMC". Each card's row is its T20 win-rate difference against a blank at the
median priority (`ablation.py`'s cache, the table's own numbers). A row is a
fact about the list and the pod it was measured at, so REGENERATE THIS AFTER
EVERY REBUILD of a listed deck (`tests.test_return_rank` fails when the
file and the cache disagree). Only the decks in `DECKS` are read.
"""
import json
import os
import sys

DECKS = {"azusa": "results/caches/ablation_cache_azusa_10-20_n15000_medblank.json"}
OUT = "edhmc/decks/_return_rank.py"


def derive() -> dict:
    out = {}
    for deck, path in DECKS.items():
        d = json.load(open(path))
        out[deck] = {k: round(v["20"]["won"][0], 6) for k, v in sorted(d.items())
                     if isinstance(v, dict) and "20" in v}
    return out


def render(rank: dict) -> str:
    lines = ['"""GENERATED by `python -m tools.return_rank --write` (§0z277): each',
             "card's T20 win-rate row from its deck's ablation cache. Do not edit;",
             'regenerate after a rebuild."""', "", "SOURCES = {"]
    for deck, path in DECKS.items():
        lines.append(f"    {deck!r}: {path!r},")
    lines += ["}", "", "RANK = {"]
    for deck, rows in rank.items():
        lines.append(f"    {deck!r}: {{")
        for name, row in rows.items():
            lines.append(f"        {name!r}: {row!r},")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render(derive())
    if "--write" in sys.argv:
        open(OUT, "w").write(text)
        print(f"wrote {OUT}")
        return 0
    current = open(OUT).read() if os.path.exists(OUT) else ""
    print("CURRENT" if current == text else f"STALE: run --write ({OUT})")
    return 0 if current == text else 1


if __name__ == "__main__":
    sys.exit(main())
